function main() {
  const db = openIndexDb();
  const provider = getProviderConfig();
  let genericSeededCount = 0;
  let exactSeededCount = 0;

  for (const [rawSourceText, rawTranslatedText] of TRANSLATIONS) {
    const sourceText = normalizeSourceText(rawSourceText);
    const translatedText = normalizeTranslatedText(rawTranslatedText, sourceText);
    const genericKey = buildGenericKey(sourceText);
    db.upsertTranslation({
      genericKey,
      sourceText,
      translatedText,
      provider: "seeded-as2-script",
      model: provider.model,
      styleVersion: STYLE_VERSION
    });
    genericSeededCount += 1;
    exactSeededCount += db.upsertExactTranslationsForSource({
      sourceText,
      translatedText,
      provider: "seeded-as2-script",
      model: provider.model,
      styleVersion: STYLE_VERSION
    });
  }

  db.close();
  printJson({
    ok: true,
    translationCount: TRANSLATIONS.length,
    genericSeededCount,
    exactSeededCount,
    provider: "seeded-as2-script",
    styleVersion: STYLE_VERSION
  });
}

main();
